//! Generates the living status documents under `docs/planning/generated/`:
//! the parity-floor table and the milestone scorecard. Both are committed
//! artifacts; `ci` regenerates them so they cannot drift from the gates.

use crate::util::workspace_root;

const PARITY: &str = r#"\
# Parity floors (rising-only)

Generated by `cargo run -p xtask -- parity`; do not edit by hand.
Floors only move up. Lowering a floor is a defect: reopen the milestone
that set it instead.

| Metric | Floor | Set in | Enforced by |
|---|---|---|---|
| corpus files parsed without panic | 0 | M0 | `xtask corpus` (active from M2) |
| fwpng round-trip byte-identical files | 0 | M0 | corpus gate (M2) |
| wasm-clean crates | 4 | M0 | `xtask wasm` |
| layer-table violations | 0 | M0 | `xtask layers` |
"#;

const SCORECARD: &str = r#"\
# FireCraft scorecard

Generated by `cargo run -p xtask -- scorecard`; do not edit by hand.
A milestone flips to done only when its gate evidence is recorded in
`log/devlog.md`.

| Milestone | Status | Gate evidence |
|---|---|---|
| M0 workspace bootstrap | in progress | `xtask ci` |
| M1 foundations (blend modes, gradients, JS engine spike) | not started | — |
| M2 fwpng read path + corpus | not started | — |
| M3 document model + round-trip | not started | — |
| M4 CPU compositor | not started | — |
| M5 editor shell (native + web) | not started | — |
| M6 vector depth | not started | — |
| M7 bitmap + filters | not started | — |
| M8 import/export | not started | — |
| M9 scripting + automation | not started | — |
| M10 symbols + shared content | not started | — |
| M11 web export pipeline | not started | — |
| M12 parity + release matrix | not started | — |
"#;

/// Writes `docs/planning/generated/parity.md`.
pub fn parity() -> Result<(), String> {
    write("docs/planning/generated/parity.md", PARITY)
}

/// Writes `docs/planning/generated/scorecard.md`.
pub fn scorecard() -> Result<(), String> {
    write("docs/planning/generated/scorecard.md", SCORECARD)
}

fn write(rel: &str, content: &str) -> Result<(), String> {
    let path = workspace_root().join(rel);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    std::fs::write(&path, content).map_err(|e| format!("write {}: {e}", path.display()))
}
