/// Writes `docs/planning/generated/parity.md`.
pub fn parity() -> Result<(), String> {
    write("docs/planning/generated/parity.md", PARITY)
}

/// Writes `docs/planning/generated/scorecard.md`.
pub fn scorecard() -> Result<(), String> {
    write("docs/planning/generated/scorecard.md", SCORECARD)
}

fn write(rel: &str, content: &str) -> Result<(), String> {
    let path = workspace_root().join(rel);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    std::fs::write(&path, content).map_err(|e| format!("write {}: {e}", path.display()))
}
