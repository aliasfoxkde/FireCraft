//! The published shortcut table: `docs/SHORTCUTS.md`, generated from
//! the same keymap tables the shell dispatches from.
//!
//! The table is written, not hand-maintained: the shell's keymap
//! module is the only source, so a binding that changes in the code
//! changes in the document in the same commit. The gate compares the
//! committed file against a fresh render and fails on any difference —
//! a hand-edit of the document is a defect, not a preference.

use app::keymap::KeymapSet;
use app::menus::{Action, Shortcut};

use crate::util::workspace_root;

/// The committed document.
pub const DOCUMENT: &str = "docs/SHORTCUTS.md";

/// The gate: render the table and compare it with the committed file.
pub fn run() -> Result<(), String> {
    run_inner(false)
}

/// `xtask shortcuts --bless`: rewrite the document from the tables.
pub fn bless() -> Result<(), String> {
    run_inner(true)
}

fn run_inner(bless: bool) -> Result<(), String> {
    let rendered = render();
    let path = workspace_root().join(DOCUMENT);
    if bless {
        std::fs::write(&path, &rendered).map_err(|e| format!("write {}: {e}", path.display()))?;
        eprintln!("[xtask] shortcuts --bless: wrote {DOCUMENT}");
        return Ok(());
    }
    let committed = std::fs::read_to_string(&path).map_err(|e| {
        format!(
            "read {}: {e} (run `cargo run -p xtask -- shortcuts --bless`)",
            path.display()
        )
    })?;
    if committed == rendered {
        return Ok(());
    }
    Err(format!(
        "{DOCUMENT} does not match the keymap tables.\n\
         The table is generated; run `cargo run -p xtask -- shortcuts --bless`\n\
         to rewrite it, or commit the change that moved the bindings."
    ))
}

/// The CS6 binding for one verb, if the CS6 table binds it.
fn cs6_binding(action: Action) -> Option<Shortcut> {
    app::menus::SHORTCUTS
        .iter()
        .find(|shortcut| shortcut.action == action)
        .copied()
}

/// The rendered document.
fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "# FireCraft keyboard shortcuts\n\
         \n\
         Generated by `cargo run -p xtask -- shortcuts --bless`; do not edit by\n\
         hand. The document is written from the same keymap tables the shell\n\
         dispatches from, so it cannot drift from the code — the gate fails on\n\
         any difference.\n\
         \n\
         FireCraft ships one keymap set by default — CS6's own, taken from the\n\
         CS6 `Fireworks.xml` keymap resource — and four alternatives that\n\
         rebind the shared verbs. Edit ▸ Preferences ▸ Keyboard chooses the\n\
         set; the in-force bindings are also listed in the app's own\n\
         **Keyboard Shortcuts** panel (F1).\n",
    );
    for set in KeymapSet::ALL {
        out.push('\n');
        out.push_str(&format!("## {}\n\n", set.label()));
        out.push_str(&format!("Source: {}.\n\n", set.source()));
        if set == KeymapSet::Cs6 {
            out.push_str("Every binding the shell knows, in the CS6 menu sections.\n\n");
            out.push_str("| Section | Verb | Keys |\n|---|---|---|\n");
            for shortcut in app::menus::SHORTCUTS {
                out.push_str(&format!(
                    "| {} | {} | {} |\n",
                    shortcut.group,
                    app::menus::action_name(shortcut.action),
                    shortcut.label(),
                ));
            }
            continue;
        }
        out.push_str(
            "The verbs this set rebinds. Every other verb keeps the CS6 binding, so\n\
             the set is never a regression against the default. The last column is\n\
             the vendor's own name for the command, so the row can be found in the\n\
             source named above.\n\n",
        );
        out.push_str("| Section | Verb | Keys | CS6 | Vendor command |\n|---|---|---|---|---|\n");
        for binding in set.overrides() {
            let section = cs6_binding(binding.action)
                .map(|shortcut| shortcut.group.to_owned())
                .unwrap_or_default();
            let cs6 = cs6_binding(binding.action)
                .map(|shortcut| shortcut.label())
                .unwrap_or_else(|| "—".to_owned());
            let shortcut = Shortcut {
                group: "",
                mods: binding.mods,
                key: binding.key,
                action: binding.action,
            };
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} |\n",
                section,
                app::menus::action_name(binding.action),
                shortcut.label(),
                cs6,
                binding.vendor_command,
            ));
        }
    }
    out
}
