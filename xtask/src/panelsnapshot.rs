//! Panel snapshot gate: the CS6 panel inventory the shell draws,
//! pinned against a committed golden file.
//!
//! `egui_kittest` — the snapshot library the quality-gates section of
//! `docs/NEXT.md` names — was checked before this gate was written
//! (2026-11-10):
//!
//! - It is *obtainable*: `egui_kittest` 0.36.2 is on crates.io and
//!   requires `egui ^0.36.2`, which is exactly the egui this
//!   repository's lockfile pins. The CI image is not offline either —
//!   it runs with `CARGO_NET_OFFLINE=false` (decision 0073: the baked
//!   registry cache is a fast floor, not a wall), so a crate the cache
//!   lacks is fetched, not refused.
//! - Its *pixel* path is the blocker: the snapshot machinery sits
//!   behind the crate's optional `wgpu` / `egui-wgpu` features, and
//!   the CI image installs no graphics stack (no mesa, no Vulkan
//!   drivers), so a wgpu adapter is not available in the sandbox. A
//!   pixel suite would fail there for want of an adapter, not for
//!   want of a crate.
//!
//! So the panel set is pinned the way this repository pins everything
//! else — a committed golden file, compared against a freshly
//! rendered snapshot, regenerated deliberately. Pixel snapshots stay
//! open until the CI image can prove a software adapter; see
//! decision 0087.
//!
//! What is pinned is the panel *structure*: the set, the dock order,
//! the dock side, the header text, the fresh-document visibility, and
//! whether the Window menu can toggle the panel. A panel added,
//! renamed, reordered, or re-docked without a deliberate re-pin fails
//! the build. The content a panel draws is not pinned — it changes
//! with every feature, and such a change is reviewed as code.

use app::shell::{PanelSummary, panel_inventory};

use crate::util::workspace_root;

/// The committed golden file.
pub const GOLDEN: &str = "crates/app/panels.snapshot";

/// The header written above the snapshot records.
const SNAPSHOT_HEADER: &str = "\
# FireCraft panel snapshot — the CS6 panel inventory as the shell draws it.
#
# Generated by `cargo run -p xtask -- panel-snapshot --bless`; do not
# edit by hand. A panel added, renamed, reordered, or re-docked without
# a deliberate re-pin fails the build.
#
# id	side	order	header	visible	toggleable
";

/// The gate: render the panel inventory and compare it with the golden.
pub fn run() -> Result<(), String> {
    run_inner(false)
}

/// `xtask panel-snapshot --bless`: rewrite the golden from the live
/// panel inventory.
pub fn bless() -> Result<(), String> {
    run_inner(true)
}

fn run_inner(bless: bool) -> Result<(), String> {
    let inventory = panel_inventory();
    let rendered = render(&inventory);
    let path = workspace_root().join(GOLDEN);
    if bless {
        std::fs::write(&path, &rendered).map_err(|e| format!("write {}: {e}", path.display()))?;
        eprintln!(
            "[xtask] panel-snapshot --bless: wrote {GOLDEN} ({} panel(s))",
            inventory.len()
        );
        return Ok(());
    }
    let committed = std::fs::read_to_string(&path).map_err(|e| {
        format!(
            "read {}: {e} — run `cargo run -p xtask -- panel-snapshot --bless`",
            path.display()
        )
    })?;
    compare(&rendered, &committed)
}

/// The snapshot text for one panel inventory.
fn render(inventory: &[PanelSummary]) -> String {
    let mut out = String::from(SNAPSHOT_HEADER);
    for panel in inventory {
        out.push_str(&format!(
            "{}\t{}\t{}\t{}\t{}\t{}\n",
            panel.id,
            panel.side.as_str(),
            panel.order,
            panel.header,
            panel.visible_by_default,
            panel.toggleable
        ));
    }
    out
}

/// Compares the rendered snapshot with the committed golden.
///
/// This is the decision core: it takes the two texts as data and
/// answers "did the panel set change?". It reads no process state, so
/// a test can drive it with a deliberately altered panel.
fn compare(rendered: &str, committed: &str) -> Result<(), String> {
    if rendered == committed {
        return Ok(());
    }
    let rendered_lines: Vec<&str> = rendered.lines().collect();
    let committed_lines: Vec<&str> = committed.lines().collect();
    let mut differences = Vec::new();
    let rows = rendered_lines.len().max(committed_lines.len());
    for index in 0..rows {
        let rendered_line = rendered_lines.get(index);
        let committed_line = committed_lines.get(index);
        match (rendered_line, committed_line) {
            (Some(rendered_line), Some(committed_line)) => {
                if rendered_line != committed_line {
                    differences.push(format!(
                        "line {}: golden `{committed_line}` != panel set `{rendered_line}`",
                        index + 1
                    ));
                }
            }
            (Some(rendered_line), None) => differences.push(format!(
                "line {}: panel set `{rendered_line}` is not in the golden",
                index + 1
            )),
            (None, Some(committed_line)) => differences.push(format!(
                "line {}: golden `{committed_line}` is gone from the panel set",
                index + 1
            )),
            (None, None) => {}
        }
    }
    Err(format!(
        "panel snapshot drifted from {GOLDEN} ({} difference(s)):\n{}",
        differences.len(),
        differences.join("\n")
    ))
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod tests {
    use super::*;
    use app::shell::DockSide;

    /// One panel of a sample inventory.
    fn panel(id: &str, header: &str, order: usize) -> PanelSummary {
        PanelSummary {
            id: id.to_owned(),
            header: header.to_owned(),
            side: DockSide::Right,
            order,
            visible_by_default: true,
            toggleable: true,
        }
    }

    /// A two-panel sample inventory.
    fn sample() -> Vec<PanelSummary> {
        vec![
            panel("properties", "Properties", 0),
            panel("pages", "Pages", 1),
        ]
    }

    #[test]
    fn an_unchanged_panel_set_diffs_clean() {
        let inventory = sample();
        let snapshot = render(&inventory);
        assert!(compare(&snapshot, &snapshot).is_ok());
    }

    /// The discriminating counterexample: a panel whose header changed
    /// no longer matches the golden, and the gate says so.
    #[test]
    fn an_altered_panel_fails_the_comparison() {
        let inventory = sample();
        let golden = render(&inventory);
        let mut altered = inventory.clone();
        altered[0].header = "Properties (renamed)".to_owned();
        let error = compare(&render(&altered), &golden)
            .expect_err("an altered panel must fail the snapshot gate");
        assert!(error.contains("Properties"), "{error}");
        assert!(error.contains("renamed"), "{error}");
    }

    /// A panel that joins or leaves the set changes the row count, and
    /// the gate names both sides of the change.
    #[test]
    fn a_changed_panel_set_changes_the_row_count() {
        let inventory = sample();
        let golden = render(&inventory);
        let mut grown = inventory.clone();
        grown.push(panel("history", "History", 2));
        let error = compare(&render(&grown), &golden)
            .expect_err("an added panel must fail the snapshot gate");
        assert!(error.contains("history"), "{error}");
    }

    /// The live inventory still matches the committed golden — the
    /// gate's own check, run as a test so `cargo test -p xtask` fails
    /// on a panel that moved without a re-pin.
    #[test]
    fn the_live_panel_set_matches_the_committed_golden() {
        let path = workspace_root().join(GOLDEN);
        let committed = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        compare(&render(&panel_inventory()), &committed).unwrap_or_else(|e| panic!("{e}"));
    }
}
