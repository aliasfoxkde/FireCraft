#!/usr/bin/env python3
"""Self-test for `scripts/reconcile_deployment.py`.

The tool compares a deployment with a release bundle by digest, so the
cases that matter are the ways the two can disagree: a file whose bytes
differ, a file the deployment does not serve, a file the deployment
serves that the bundle does not name, and — the case that must not
regress — the two being identical.

The test serves two directories over a local HTTP server and runs the
comparison against them.

Usage:
    python3 -I scripts/reconcile_deployment-selftest.py
"""

import http.server
import importlib.util
import pathlib
import shutil
import sys
import tempfile
import threading

HERE = pathlib.Path(__file__).resolve().parent
TOOL = HERE / "reconcile_deployment.py"


def load_tool():
    spec = importlib.util.spec_from_file_location("reconcile_deployment", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def write_bundle(directory, files):
    """Write a bundle: the files, plus the manifest that names them."""
    directory.mkdir(parents=True, exist_ok=True)
    lines = []
    for name, payload in files.items():
        (directory / name).write_bytes(payload)
        lines.append(f"{tool.digest_of(payload)}  {name}")
    (directory / "MANIFEST.sha256").write_text(
        "# FireCraft web manifest — generated by `xtask dist`.\n" + "\n".join(lines) + "\n",
        encoding="utf-8",
    )


def serve(directory):
    """Serve a directory over HTTP on an ephemeral port."""
    handler = lambda *args, **kwargs: http.server.SimpleHTTPRequestHandler(  # noqa: E731
        *args, directory=str(directory), **kwargs
    )
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server


def main():
    global tool
    tool = load_tool()
    work = pathlib.Path(tempfile.mkdtemp(prefix="firecraft-deploy-selftest-"))
    try:
        bundle = work / "bundle"
        deployment = work / "deployment"

        # 1. Identical bundle and deployment: the report says match.
        write_bundle(bundle, {"a.js": b"alpha", "b.wasm": b"beta"})
        shutil.copytree(bundle, deployment)
        server = serve(deployment)
        try:
            url = f"http://127.0.0.1:{server.server_address[1]}"
            report = tool.compare(bundle, url)
        finally:
            server.shutdown()
        assert report["result"] == "match", report
        assert report["differences"] == [], report
        assert len(report["files"]) == 2, report
        assert report["inventory"]["only_in_bundle"] == [], report
        assert report["inventory"]["only_in_deployment"] == [], report

        # 2. A changed file: the bytes differ, and the report says so.
        (deployment / "a.js").write_bytes(b"ALPHA")
        server = serve(deployment)
        try:
            url = f"http://127.0.0.1:{server.server_address[1]}"
            report = tool.compare(bundle, url)
        finally:
            server.shutdown()
        assert report["result"] == "differences", report
        assert "a.js" in report["differences"], report
        assert "b.wasm" not in report["differences"], report

        # 3. A file the deployment does not serve, and one it serves
        #    that the bundle does not name.
        (deployment / "a.js").write_bytes(b"alpha")
        (deployment / "MANIFEST.sha256").unlink()
        write_bundle(deployment, {"a.js": b"alpha", "b.wasm": b"beta", "c.html": b"gamma"})
        server = serve(deployment)
        try:
            url = f"http://127.0.0.1:{server.server_address[1]}"
            report = tool.compare(bundle, url)
        finally:
            server.shutdown()
        assert report["result"] == "differences", report
        assert report["inventory"]["only_in_deployment"] == ["c.html"], report

        # 4. A bundle file the deployment does not serve is reported as
        #    missing rather than silently dropped.
        (deployment / "b.wasm").unlink()
        write_bundle(deployment, {"a.js": b"alpha", "c.html": b"gamma"})
        server = serve(deployment)
        try:
            url = f"http://127.0.0.1:{server.server_address[1]}"
            report = tool.compare(bundle, url)
        finally:
            server.shutdown()
        assert report["result"] == "differences", report
        assert "b.wasm" in report["differences"], report
        statuses = {row["name"]: row["status"] for row in report["files"]}
        assert statuses["b.wasm"] == "not_served", report

        print("reconcile_deployment selftest: ok")
        return 0
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
